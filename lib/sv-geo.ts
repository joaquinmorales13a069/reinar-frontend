export function getMunicipiosByDept(deptCode: string): MunicipioSV[] {
  return MUNICIPIOS_SV.filter((m) => m.department === deptCode);
}

export function resolverDepartamento(val: string | undefined | null): string {
  if (!val) return '—';
  return DEPARTAMENTOS_SV.find((d) => d.value === val)?.label ?? val;
}

export function resolverMunicipio(
  municipioVal: string | undefined | null,
  deptVal: string | undefined | null,
): string {
  if (!municipioVal) return '—';
  return (
    MUNICIPIOS_SV.find((m) => m.value === municipioVal && m.department === (deptVal ?? ''))?.label ??
    municipioVal
  );
}

