export function getDistritosByMuniDept(deptCode: string, muniCode: string): DistritoSV[] {
  return DISTRITOS_SV.filter((d) => d.department === deptCode && d.municipality === muniCode);
}

export function resolverDistrito(
  distritoVal: string | undefined | null,
  muniVal: string | undefined | null,
  deptVal: string | undefined | null,
): string {
  if (!distritoVal) return '—';
  return (
    DISTRITOS_SV.find(
      (d) => d.value === distritoVal && d.municipality === (muniVal ?? '') && d.department === (deptVal ?? ''),
    )?.label ?? distritoVal
  );
}

